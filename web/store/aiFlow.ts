/**
 * The one AI conversation: what goes into its stream besides the assistant's turns (`agentStore`) and the generation turns (`directorRun`).
 * Every entry carries an `order` taken from one counter, so the panel and the assistant's history can put the three kinds in the order they happened.
 *
 * The other thing here is the hand-over from the first-run dialog: the dialog's turns (the breakdown card, the generation card) are queued by
 * project id and become the first entries of the editor's stream when that project is opened. Client side only; a page reload clears it.
 */
import { create } from 'zustand';

let orderSeq = 0;
/** The next position in the stream (one counter for assistant runs, generation turns and hand-over entries). */
export const nextOrder = (): number => ++orderSeq;

/** A card the first-run dialog made, kept as a summary (the live progress state stays in the dialog). */
export interface OnboardEntry {
  id: number;
  order: number;
  kind: 'breakdown' | 'generate' | 'skeleton';
  /** The 「你」 bubble above the card (the first entry of a conversation carries it). */
  userText?: string;
  title: string;
  /** 「规则 / AI / 回放」 */
  who: string;
  state: 'done' | 'partial' | 'failed' | 'cancelled' | 'pending';
  /** One line, shown collapsed. */
  summary: string;
  /** What opens under 「详情」 (scene list, scenes still to do, continuity notes). */
  lines: string[];
  /** The skeleton card carries the 「生成全部场景」 button. */
  canGenerateAll?: boolean;
  /** The generation card of a run that was not finished carries 「继续生成剩余场景」 (only while scenes are still missing). */
  canResume?: boolean;
  /** The assistant's history line for this entry (it is told what happened before the editor opened). */
  historyText: string;
}

let entrySeq = 0;
export const makeEntry = (e: Omit<OnboardEntry, 'id' | 'order'>): OnboardEntry => ({ ...e, id: ++entrySeq, order: nextOrder() });

const queued = new Map<string, OnboardEntry[]>();

interface AiFlowState {
  projectId: string | null;
  entries: OnboardEntry[];
  /** Panel UI that must survive the panel being unmounted (another dock tab in front): the 「生成 ▾」 popover and the continuity block. */
  popoverOpen: boolean;
  continuityOpen: boolean;
  /** Set when entries were handed over: the editor brings the AI panel to the front once. */
  reveal: boolean;
  clearReveal(): void;
  setPopoverOpen(open: boolean): void;
  setContinuityOpen(open: boolean): void;
  /** Queue entries for a project that is not open yet; delivered by `bind`. When it is the open project they appear at once. */
  queue(projectId: string, entries: OnboardEntry[]): void;
  bind(projectId: string | null): void;
  unbind(): void;
  /** The skeleton card's button was used (or the person generated by other means): drop the card. */
  dismiss(id: number): void;
}

export const useAiFlow = create<AiFlowState>((set, get) => ({
  projectId: null,
  entries: [],
  popoverOpen: false,
  continuityOpen: false,
  reveal: false,
  clearReveal: () => set({ reveal: false }),
  setPopoverOpen: (popoverOpen) => set({ popoverOpen }),
  setContinuityOpen: (continuityOpen) => set({ continuityOpen }),
  queue(projectId, entries) {
    if (!projectId || entries.length === 0) return;
    if (get().projectId === projectId) {
      set((s) => ({ entries: [...s.entries, ...entries] }));
      return;
    }
    queued.set(projectId, [...(queued.get(projectId) ?? []), ...entries]);
  },
  bind(projectId) {
    if (get().projectId === projectId) return;
    const waiting = projectId ? queued.get(projectId) ?? [] : [];
    // delivered once, but not before the current tick is over: React's strict mode binds, unbinds and binds again right away
    if (projectId && waiting.length > 0) setTimeout(() => queued.delete(projectId), 0);
    set({ projectId, entries: waiting, popoverOpen: false, continuityOpen: false, reveal: waiting.length > 0 });
  },
  unbind() {
    set({ projectId: null, entries: [], popoverOpen: false, continuityOpen: false, reveal: false });
  },
  dismiss(id) {
    set((s) => ({ entries: s.entries.filter((e) => e.id !== id) }));
  },
}));
